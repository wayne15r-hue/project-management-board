create or replace function public.desk_context() returns jsonb
language sql stable security definer set search_path=public as $$
 select coalesce(jsonb_agg(jsonb_build_object('id',t.id,'name',t.name,'admin',desk_is_admin(t.id),'support',desk_is_support(t.id),'members',
 (select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'name',coalesce(nullif(p.full_name,''),p.email),'role',tm.role,'support',desk_is_support(t.id,p.id)) order by p.full_name,p.id),'[]')
 from team_members tm join profiles p on p.id=tm.user_id where tm.team_id=t.id)) order by t.name,t.id),'[]')
 from teams t where desk_is_member(t.id)
$$;
revoke all on function desk_context() from public,anon;
grant execute on function desk_context() to authenticated;
create or replace function public.desk_mark_all_notifications_read() returns void
language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is null then raise exception 'Authentication required' using errcode='42501'; end if;
 update notifications set read_at=now() where recipient_id=auth.uid() and read_at is null and workflow_user_board_access(board_id);
 update desk_notifications set read_at=now() where recipient_id=auth.uid() and read_at is null and desk_can_read(ticket_id);
end$$;
revoke all on function desk_mark_all_notifications_read() from public,anon;
grant execute on function desk_mark_all_notifications_read() to authenticated;
create or replace function public.desk_replay_attachment(p_ticket uuid,p_payload jsonb) returns jsonb
language plpgsql stable security definer set search_path=public as $$
declare prior desk_operations;
begin
 if not desk_can_read(p_ticket) then raise exception 'Ticket access denied' using errcode='42501'; end if;
 select * into prior from desk_operations where actor_id=auth.uid() and operation_id=(p_payload->>'operationId')::uuid;
 if not found then return null; end if;
 if prior.payload<>jsonb_build_object('ticket',p_ticket,'action','attachment','body',p_payload) then raise exception 'Operation conflict' using errcode='40001'; end if;
 return prior.result;
end$$;
revoke all on function desk_replay_attachment(uuid,jsonb) from public,anon;
grant execute on function desk_replay_attachment(uuid,jsonb) to authenticated;
commit;
