create or replace function public.desk_is_member(p_team uuid,p_user uuid default auth.uid()) returns boolean
language sql stable security definer set search_path=public as $$
 select p_user is not null and exists(select 1 from team_members where team_id=p_team and user_id=p_user)
$$;
create or replace function public.desk_is_admin(p_team uuid,p_user uuid default auth.uid()) returns boolean
language sql stable security definer set search_path=public as $$
 select exists(select 1 from team_members where team_id=p_team and user_id=p_user and role in ('owner','admin'))
$$;
create or replace function public.desk_is_support(p_team uuid,p_user uuid default auth.uid()) returns boolean
language sql stable security definer set search_path=public as $$
 select desk_is_member(p_team,p_user) and (desk_is_admin(p_team,p_user) or exists(select 1 from desk_agents where team_id=p_team and user_id=p_user))
$$;
create or replace function public.desk_can_read(p_ticket uuid,p_user uuid default auth.uid()) returns boolean
language sql stable security definer set search_path=public as $$
 select exists(select 1 from desk_tickets t where t.id=p_ticket and desk_is_member(t.team_id,p_user)
 and (t.requester_id=p_user or t.approver_id=p_user or desk_is_support(t.team_id,p_user)))
$$;

