create or replace function public.desk_validate_fields(p_type text,p_fields jsonb) returns void
language plpgsql set search_path=public as $$
declare k text; required text[];
begin
 if p_fields is null or jsonb_typeof(p_fields)<>'object' or octet_length(p_fields::text)>20000 then raise exception 'Invalid request fields' using errcode='22023'; end if;
 if exists(select 1 from jsonb_each(p_fields) e where length(e.key)>50 or jsonb_typeof(e.value)<>'string' or length(e.value#>>'{}')>5000) then raise exception 'Request fields must be strings with keys up to 50 and values up to 5000 characters' using errcode='22023'; end if;
 required:=case p_type when 'it_issue' then array['system','impact'] when 'access_request' then array['system','access_level','reason'] when 'purchase_request' then array['tool','cost','currency','reason'] when 'technical_request' then array['system','expected_behavior'] else null end;
 if required is null then raise exception 'Invalid request type' using errcode='22023'; end if;
 foreach k in array required loop
 if length(trim(coalesce(p_fields->>k,'')))=0 or length(p_fields->>k)>5000 then raise exception 'Request field % is required (maximum 5000 characters)',k using errcode='22023'; end if;
 end loop;
 if p_type='purchase_request' and (coalesce(p_fields->>'cost','') !~ '^[0-9]{1,10}(\.[0-9]{1,2})?$' or coalesce(p_fields->>'currency','') !~ '^[A-Z]{3}$') then raise exception 'Enter a valid cost and three-letter currency' using errcode='22023'; end if;
end$$;

create or replace function public.desk_set_agent(p_team uuid,p_user uuid,p_enabled boolean) returns void
language plpgsql security definer set search_path=public as $$
begin
 perform 1 from team_members where team_id=p_team order by user_id for share;
 if not desk_is_admin(p_team) then raise exception 'Team admin required' using errcode='42501'; end if;
 if p_enabled then
 if not desk_is_member(p_team,p_user) then raise exception 'Agent must be a team member' using errcode='22023'; end if;
 insert into desk_agents values(p_team,p_user) on conflict do nothing;
 else delete from desk_agents where team_id=p_team and user_id=p_user; end if;
end$$;

-- Internal event producer: never executable by clients. State and notifications commit together.
create or replace function public.desk_event(p_ticket uuid,p_action text,p_details jsonb default '{}') returns void
language plpgsql security definer set search_path=public as $$
declare t desk_tickets; e uuid; r uuid;
begin
 select * into t from desk_tickets where id=p_ticket;
 insert into desk_activity(ticket_id,actor_id,action,details) values(p_ticket,auth.uid(),p_action,p_details) returning id into e;
 if p_action in ('assign','request_approval','approve','request_changes','reject','comment','reopen','resolved') then
 for r in select distinct u from unnest(array[t.requester_id,t.assignee_id,case when t.approval_status='pending' or p_action in ('approve','request_changes','reject') then t.approver_id end]) u loop
 if r is not null and r<>auth.uid() and desk_can_read(p_ticket,r) then
 insert into desk_notifications(ticket_id,recipient_id,actor_id,event_id,type,title,body)
 values(p_ticket,r,auth.uid(),e,p_action,'SD-'||lpad(t.number::text,6,'0')||' · '||t.title,replace(p_action,'_',' '));
 end if;
 end loop;
 end if;
end$$;

create or replace function public.desk_create_ticket(p_team uuid,p_payload jsonb) returns jsonb
language plpgsql security definer set search_path=public as $$
declare t desk_tickets; old desk_operations; key uuid; payload jsonb;
begin
 perform 1 from team_members where team_id=p_team order by user_id for share;
 if not desk_is_member(p_team) then raise exception 'Team membership required' using errcode='42501'; end if;
 key:=(p_payload->>'operationId')::uuid;
 if key is null then raise exception 'Operation ID required' using errcode='22023'; end if;
 perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text||key::text,0));
 payload:=jsonb_build_object('team',p_team,'create',p_payload);
 select * into old from desk_operations where actor_id=auth.uid() and operation_id=key;
 if found then
 if old.payload<>payload then raise exception 'Operation conflict' using errcode='40001'; end if;
 return old.result; end if;
 perform desk_validate_fields(p_payload->>'type',coalesce(p_payload->'fields','{}'));
 insert into desk_tickets(team_id,requester_id,title,description,type,priority,fields)
 values(p_team,auth.uid(),trim(p_payload->>'title'),trim(p_payload->>'description'),p_payload->>'type',coalesce(p_payload->>'priority','medium'),p_payload->'fields') returning * into t;
 perform desk_event(t.id,'created');
 insert into desk_operations values(auth.uid(),key,payload,to_jsonb(t));
 return to_jsonb(t);
end$$;

create or replace function public.desk_ticket_action(p_ticket uuid,p_action text,p_payload jsonb) returns jsonb
language plpgsql security definer set search_path=public as $$
<<mutation>>
declare t desk_tickets; old desk_operations; payload jsonb; key uuid; support boolean; requester boolean;
 next_status text; note text; target uuid; a desk_approvals; changed boolean; path text;
begin
 -- Lock membership rows before the ticket so access removal cannot race an authorized mutation.
 perform 1 from team_members where team_id=(select team_id from desk_tickets where id=p_ticket) order by user_id for share;
 select * into t from desk_tickets where id=p_ticket for update;
 if t.id is null or not desk_can_read(p_ticket) then raise exception 'Ticket access denied' using errcode='42501'; end if;
 support:=desk_is_support(t.team_id); requester:=t.requester_id=auth.uid();
 key:=(p_payload->>'operationId')::uuid;
 if key is null then raise exception 'Operation ID required' using errcode='22023'; end if;
 perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text||key::text,0));
 payload:=jsonb_build_object('ticket',p_ticket,'action',p_action,'body',p_payload);
 select * into old from desk_operations where actor_id=auth.uid() and operation_id=key;
 if found then
 if old.payload<>payload then raise exception 'Operation conflict' using errcode='40001'; end if;
 return old.result; end if;
 if (p_payload->>'expectedRevision')::integer is distinct from t.revision then raise exception 'Ticket revision changed. Refresh and try again.' using errcode='40001'; end if;
 note:=nullif(trim(p_payload->>'note'),'');
 if length(note)>5000 then raise exception 'Note exceeds 5000 characters' using errcode='22023'; end if;
 if p_action='edit' then
 if not (support or requester) then raise exception 'Requester or support required' using errcode='42501'; end if;
 if t.work_started or t.status not in ('submitted','triage','waiting') then raise exception 'Return to triage or reopen before editing' using errcode='22023'; end if;
 changed:=false;
 if p_payload ? 'title' and (p_payload->>'title') is distinct from t.title then t.title:=trim(p_payload->>'title'); changed:=true; end if;
 if p_payload ? 'description' and (p_payload->>'description') is distinct from t.description then t.description:=trim(p_payload->>'description'); changed:=true; end if;
 if p_payload ? 'fields' and (p_payload->'fields') is distinct from t.fields then t.fields:=p_payload->'fields'; changed:=true; end if;
 perform desk_validate_fields(t.type,t.fields);
 if changed then
 t.revision:=t.revision+1; t.approval_status:='not_requested'; t.status:='triage'; t.waiting_reason:=null;
 update desk_approvals set status='superseded',decided_at=now() where ticket_id=t.id and status in ('pending','approved');
 end if;
 elsif p_action='assign' then
 if not support then raise exception 'Support required' using errcode='42501'; end if;
 target:=nullif(p_payload->>'assigneeId','')::uuid;
 if target is not null and not desk_is_support(t.team_id,target) then raise exception 'Assignee must be current support staff' using errcode='22023'; end if;
 if target is not null and target=t.approver_id then raise exception 'Assignee and approver must be independent' using errcode='22023'; end if;
 t.assignee_id:=target;
 elsif p_action='manage' then
 if not support then raise exception 'Support required' using errcode='42501'; end if;
 if p_payload ? 'priority' then t.priority:=p_payload->>'priority'; end if;
 if p_payload ? 'dueDate' then t.due_date:=nullif(p_payload->>'dueDate','')::date; end if;
 elsif p_action='request_approval' then
 if not support then raise exception 'Support required' using errcode='42501'; end if;
 if t.status in ('in_progress','resolved','closed','cancelled') then raise exception 'Return to triage before requesting approval' using errcode='22023'; end if;
 target:=(p_payload->>'approverId')::uuid;
 if target is null or not desk_is_member(t.team_id,target) or target=t.requester_id or target=t.assignee_id then raise exception 'A current independent approver is required' using errcode='22023'; end if;
 update desk_approvals set status='superseded',decided_at=now() where ticket_id=t.id and status in ('pending','approved');
 insert into desk_approvals(ticket_id,revision,approver_id,status) values(t.id,t.revision,target,'pending');
 t.approver_id:=target; t.approval_status:='pending'; t.status:='waiting'; t.waiting_reason:='approval';
 elsif p_action in ('approve','request_changes','reject') then
 if auth.uid() is distinct from t.approver_id or auth.uid()=t.requester_id or auth.uid()=t.assignee_id then raise exception 'Assigned independent approver required' using errcode='42501'; end if;
 select * into a from desk_approvals where ticket_id=t.id and status='pending' for update;
 if a.id is null or a.revision<>t.revision or t.approval_status<>'pending' then raise exception 'No pending approval for this revision' using errcode='40001'; end if;
 if p_action<>'approve' and note is null then raise exception 'Decision reason required' using errcode='22023'; end if;
 t.approval_status:=case p_action when 'approve' then 'approved' when 'reject' then 'rejected' else 'changes_requested' end;
 t.status:='triage'; t.waiting_reason:=null;
 update desk_approvals set status=t.approval_status,note=mutation.note,decided_at=now() where id=a.id;
 elsif p_action='status' then
 next_status:=p_payload->>'status';
 if not support and not (requester and (
 (next_status='cancelled' and t.status in ('submitted','triage','waiting','in_progress')) or
 (next_status='closed' and t.status='resolved') or
 (next_status='triage' and t.status in ('resolved','closed')))) then raise exception 'Support required for this transition' using errcode='42501'; end if;
 if next_status=t.status then raise exception 'Ticket already has this status' using errcode='22023'; end if;
 if not ((t.status='submitted' and next_status in ('triage','waiting','cancelled')) or
 (t.status='triage' and next_status in ('in_progress','waiting','cancelled')) or
 (t.status='waiting' and next_status in ('triage','in_progress','cancelled')) or
 (t.status='in_progress' and next_status in ('triage','waiting','resolved','cancelled')) or
 (t.status='resolved' and next_status in ('closed','triage')) or
 (t.status='closed' and next_status='triage')) then raise exception 'Invalid ticket status transition' using errcode='22023'; end if;
 if next_status='waiting' then
 t.waiting_reason:=p_payload->>'waitingReason';
 if t.waiting_reason is null or t.waiting_reason not in ('requester_information','approval') or note is null then raise exception 'Waiting reason and note required' using errcode='22023'; end if;
 if t.waiting_reason='approval' and t.approval_status<>'pending' then raise exception 'Request approval first' using errcode='22023'; end if;
 else t.waiting_reason:=null; end if;
 if next_status in ('in_progress','resolved') then
 if t.assignee_id is null or not desk_is_support(t.team_id,t.assignee_id) then raise exception 'Assign current support staff before fulfillment' using errcode='22023'; end if;
 if (t.type in ('access_request','purchase_request') or t.approver_id is not null) and
 (t.approval_status<>'approved' or not desk_is_member(t.team_id,t.approver_id)) then raise exception 'Current independent approval required before fulfillment' using errcode='22023'; end if;
 end if;
 if next_status='in_progress' then t.work_started:=true; end if;
 if next_status='resolved' then
 if note is null then raise exception 'Resolution note required' using errcode='22023'; end if;
 t.resolution_note:=note;
 end if;
 if next_status='triage' and (t.status in ('resolved','closed','in_progress') or t.work_started) then
 if note is null then raise exception 'Reopen or return-to-triage reason required' using errcode='22023'; end if;
 t.revision:=t.revision+1; t.approval_status:='not_requested'; t.resolution_note:=null; t.work_started:=false;
 update desk_approvals set status='superseded',decided_at=now() where ticket_id=t.id and status in ('pending','approved');
 if t.status in ('resolved','closed') then p_action:='reopen'; end if;
 end if;
 if next_status in ('cancelled','closed') and t.approval_status='pending' then
 update desk_approvals set status='superseded',decided_at=now() where ticket_id=t.id and status='pending';
 t.approval_status:='not_requested';
 end if;
 t.status:=next_status;
 if next_status='resolved' then p_action:='resolved'; end if;
 elsif p_action='comment' then
 if t.status in ('closed','cancelled') then raise exception 'Reopen before commenting' using errcode='22023'; end if;
 insert into desk_comments(ticket_id,author_id,text) values(t.id,auth.uid(),trim(p_payload->>'text'));
 elsif p_action='link' then
 if not support then raise exception 'Support required' using errcode='42501'; end if;
 target:=(p_payload->>'cardId')::uuid;
 if not exists(select 1 from cards c join board_teams bt on bt.board_id=c.board_id where c.id=target and bt.team_id=t.team_id and user_has_board_access(c.board_id)) then raise exception 'Task board must belong to this team and be accessible' using errcode='42501'; end if;
 if coalesce((p_payload->>'remove')::boolean,false) then delete from desk_ticket_links where ticket_id=t.id and card_id=target;
 else insert into desk_ticket_links values(t.id,target) on conflict do nothing; end if;
 elsif p_action='attachment' then
 if not (support or requester) then raise exception 'Requester or support required to upload' using errcode='42501'; end if;
 if t.work_started or t.status in ('closed','cancelled','resolved','in_progress') then raise exception 'Return to triage or reopen before attaching request material' using errcode='22023'; end if;
 path:=p_payload->>'storagePath';
 if split_part(path,'/',1)<>t.id::text or not exists(select 1 from storage.objects where bucket_id='desk-attachments' and name=path) then raise exception 'Uploaded attachment not found' using errcode='22023'; end if;
 insert into desk_attachments(ticket_id,uploaded_by,file_name,file_type,file_size,storage_path)
 values(t.id,auth.uid(),p_payload->>'fileName',p_payload->>'fileType',(p_payload->>'fileSize')::bigint,path);
 t.revision:=t.revision+1; t.approval_status:='not_requested'; t.status:='triage'; t.waiting_reason:=null;
 update desk_approvals set status='superseded',decided_at=now() where ticket_id=t.id and status in ('pending','approved');
 else raise exception 'Unknown ticket action' using errcode='22023'; end if;
 update desk_tickets set title=t.title,description=t.description,fields=t.fields,priority=t.priority,status=t.status,
 waiting_reason=t.waiting_reason,assignee_id=t.assignee_id,approver_id=t.approver_id,approval_status=t.approval_status,
 revision=t.revision,work_started=t.work_started,resolution_note=t.resolution_note,due_date=t.due_date,updated_at=now() where id=t.id returning * into t;
 perform desk_event(t.id,p_action,p_payload-'operationId'-'expectedRevision'-'storagePath');
 insert into desk_operations values(auth.uid(),key,payload,to_jsonb(t));
 return to_jsonb(t);
end$$;

