create or replace function public.desk_storage_read(p_path text) returns boolean
language plpgsql stable security definer set search_path=public as $$
begin return desk_can_read(split_part(p_path,'/',1)::uuid); exception when invalid_text_representation then return false; end$$;
create or replace function public.desk_storage_write(p_path text) returns boolean
language plpgsql stable security definer set search_path=public as $$
declare t desk_tickets;
begin
 select * into t from desk_tickets where id=split_part(p_path,'/',1)::uuid;
 return desk_is_member(t.team_id) and (t.requester_id=auth.uid() or desk_is_support(t.team_id)) and not t.work_started and t.status in ('submitted','triage','waiting');
exception when invalid_text_representation then return false; end$$;
drop policy if exists desk_storage_select on storage.objects;
-- Intentionally no authenticated SELECT policy: prevents client-created signed URLs.
drop policy if exists desk_storage_insert on storage.objects;
create policy desk_storage_insert on storage.objects for insert to authenticated with check(bucket_id='desk-attachments' and desk_storage_write(name));
drop policy if exists desk_storage_delete on storage.objects;
create policy desk_storage_delete on storage.objects for delete to authenticated using(bucket_id='desk-attachments' and desk_storage_write(name) and not exists(select 1 from desk_attachments where storage_path=name));

-- Default function grants are public in PostgreSQL: explicitly restrict every entrypoint.
revoke all on function desk_event(uuid,text,jsonb),desk_validate_fields(text,jsonb) from public,anon,authenticated;
revoke all on function desk_is_member(uuid,uuid),desk_is_admin(uuid,uuid),desk_is_support(uuid,uuid),desk_can_read(uuid,uuid),desk_storage_read(text),desk_storage_write(text),desk_set_agent(uuid,uuid,boolean),desk_create_ticket(uuid,jsonb),desk_ticket_action(uuid,text,jsonb) from public,anon;
