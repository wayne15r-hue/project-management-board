import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'docs/leave-desk-holiday-references.json'), 'utf8'));
const quote = value => `'${String(value).replaceAll("'", "''")}'`;
const seen = new Set();
const rows = data.lists.flatMap(list => list.holidays.map(holiday => {
  if (!/^20(26|27)-\d{2}-\d{2}$/.test(holiday.date) || new Date(`${holiday.date}T00:00:00Z`).toISOString().slice(0, 10) !== holiday.date) throw new Error(`Invalid date in ${list.id}`);
  if (!['india_central', 'india_restricted', 'india_regional', 'us_federal'].includes(list.kind)) throw new Error('Reference kind required');
  if (list.review_status !== 'reviewed') throw new Error('Only reviewed lists may be seeded');
  const key = [holiday.date, holiday.name, list.kind, list.source].join('|');
  if (seen.has(key)) throw new Error(`Duplicate ${key}`);
  seen.add(key);
  return [holiday.date, holiday.name, list.kind, list.source, list.review_status];
}));
const sql = `-- Generated by scripts/leave-build-reference-seed.mjs from reviewed official reference facts.
-- Reference overlays ONLY. No calendars, company days off, assignments or entitlements.
begin;
insert into public.leave_holidays(calendar_id,date,name,kind,source,review_status)
select null,v.date::date,v.name,v.kind,v.source,v.review_status
from (values
${rows.map(row => `  (${row.map(quote).join(',')})`).join(',\n')}
) as v(date,name,kind,source,review_status)
where not exists(select 1 from public.leave_holidays h where h.calendar_id is null
  and h.date=v.date::date and h.name=v.name and h.kind=v.kind and h.source=v.source);
commit;
`;
const destination = path.join(root, 'supabase/migrations/20261103_zzz_leave_references.sql');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== sql) throw new Error('Reference migration is stale; run script without --check');
} else fs.writeFileSync(destination, sql);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${rows.length} reviewed overlay dates; no database connection made.`);
